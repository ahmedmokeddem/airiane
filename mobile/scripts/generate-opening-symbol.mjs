// Exact source geometry; never hand-edit the generated paths.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const source = readFileSync(new URL('../../assets/brand/logo/airiane-symbol.svg', import.meta.url), 'utf8');
const paths = [...source.matchAll(/<path d="([^"]+)"/g)].map(match => match[1]);
if (paths.length !== 2) throw new Error('Review the approved symbol before regenerating its reveal.');
function length(d) {
  const n = d.match(/-?\d+(?:\.\d+)?/g).map(Number);
  let [x,y] = n.splice(0,2), total=0;
  while(n.length) {
    const [a,b,c,e,f,g] = n.splice(0,6); let px=x,py=y;
    for(let i=1;i<=256;i++) { const t=i/256,u=1-t;const nx=u*u*u*x+3*u*u*t*a+3*u*t*t*c+t*t*t*f;const ny=u*u*u*y+3*u*u*t*b+3*u*t*t*e+t*t*t*g;total+=Math.hypot(nx-px,ny-py);px=nx;py=ny; }
    x=f;y=g;
  }
  return Math.ceil(total*100)/100;
}
writeFileSync(new URL('../src/features/opening/symbol.generated.ts',import.meta.url), `// Generated by scripts/generate-opening-symbol.mjs from the approved SVG.\nexport const symbolSourceHash = ${JSON.stringify(createHash('sha256').update(source).digest('hex'))};\nexport const symbolStrokes = ${JSON.stringify(paths.map(d=>({d,length:length(d)})),null,2)} as const;\n`);
